"""Create observability/langfuse/.env with random secrets and a ready-made project.

    python make_env.py

Langfuse starts with an organisation, a project called RegAssist, a login and a pair
of API keys already created, so there is nothing to click through. The script prints
the three lines to put in agent-orchestrator/.env and your Langfuse login.
It never overwrites an existing .env (delete it first to start over; doing so also
requires deleting the Langfuse Docker volumes, because the databases keep the old
passwords).
"""
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENV = HERE / ".env"


def token(n: int = 24) -> str:
    return secrets.token_urlsafe(n).replace("-", "a").replace("_", "b")


def main() -> None:
    if ENV.exists():
        sys.exit(f"{ENV} already exists; not overwriting it. Delete it to generate a new one.")
    postgres = token()
    minio = token()
    public_key = "pk-lf-" + secrets.token_hex(16)
    secret_key = "sk-lf-" + secrets.token_hex(16)
    password = token(12)
    lines = {
        # Web UI address (port changed from 3000 in docker-compose.override.yml)
        "NEXTAUTH_URL": "http://localhost:3100",
        "NEXTAUTH_SECRET": token(32),
        "SALT": token(32),
        "ENCRYPTION_KEY": secrets.token_hex(32),  # must be 64 hex characters
        # Databases and storage. Each password appears wherever the official file expects it.
        "POSTGRES_PASSWORD": postgres,
        "DATABASE_URL": f"postgresql://postgres:{postgres}@postgres:5432/postgres",
        "CLICKHOUSE_PASSWORD": token(),
        "REDIS_AUTH": token(),
        "MINIO_ROOT_PASSWORD": minio,
        "LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY": minio,
        "LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY": minio,
        "LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY": minio,
        # Created automatically on first start
        "LANGFUSE_INIT_ORG_ID": "regassist",
        "LANGFUSE_INIT_ORG_NAME": "RegAssist",
        "LANGFUSE_INIT_PROJECT_ID": "regassist",
        "LANGFUSE_INIT_PROJECT_NAME": "RegAssist",
        "LANGFUSE_INIT_PROJECT_PUBLIC_KEY": public_key,
        "LANGFUSE_INIT_PROJECT_SECRET_KEY": secret_key,
        "LANGFUSE_INIT_USER_EMAIL": "admin@regassist.local",
        "LANGFUSE_INIT_USER_NAME": "RegAssist Admin",
        "LANGFUSE_INIT_USER_PASSWORD": password,
    }
    ENV.write_text("# Generated by make_env.py. Local use only; never commit this file.\n"
                   + "".join(f"{k}={v}\n" for k, v in lines.items()), encoding="utf-8")
    print(f"Wrote {ENV}\n")
    print("Add these three lines to agent-orchestrator/.env:\n")
    print(f"LANGFUSE_PUBLIC_KEY={public_key}")
    print(f"LANGFUSE_SECRET_KEY={secret_key}")
    print("LANGFUSE_BASE_URL=http://127.0.0.1:3100\n")
    print("Langfuse login (http://localhost:3100):")
    print("  email:    admin@regassist.local")
    print(f"  password: {password}")


if __name__ == "__main__":
    main()
